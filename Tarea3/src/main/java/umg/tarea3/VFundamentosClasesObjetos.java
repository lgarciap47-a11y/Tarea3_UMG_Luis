    private void btnCrearArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearArtistaActionPerformed
        // TODO add your handling code here:
        String nom = txtNombre.getText().trim();
        String pais = txtPais.getText().trim();
        String oyeStr = txtOyentes.getText().trim();

        if (nom.isEmpty() || pais.isEmpty() || oyeStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos del artista.");
            return;
        }

        try {
            int oyentes = Integer.parseInt(oyeStr);
            Artista art = new Artista();
            art.nombre = nom;
            art.paisOrigen = pais;
            art.oyentesMensuales = oyentes;

            taResultados.append("--- ARTISTA REGISTRADO ---\n");
            taResultados.append("Nombre: " + art.nombre + "\n");
            taResultados.append("Pais de Origen: " + art.paisOrigen + "\n");
            taResultados.append("Oyentes Mensuales: " + art.oyentesMensuales + "\n\n");

            txtNombre.setText("");
            txtPais.setText("");
            txtOyentes.setText("");

            javax.swing.JOptionPane.showMessageDialog(this, "Artista creado exitosamente.");

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Los oyentes mensuales deben ser un numero entero.");
        }
    }//GEN-LAST:event_btnCrearArtistaActionPerformed

    private void btnCrearCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCancionActionPerformed
        // TODO add your handling code here:
        String tit = txtTitulo.getText().trim();
        String interp = txtInterprete.getText().trim();
        String durStr = txtDuracion.getText().trim();
        String gen = txtGenero.getText().trim();

        if (tit.isEmpty() || interp.isEmpty() || durStr.isEmpty() || gen.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos de la cancion.");
            return;
        }

        try {
            int duracion = Integer.parseInt(durStr);

            Cancion can = new Cancion();
            can.titulo = tit;
            can.nombreArtista = interp;
            can.duracionSegundos = duracion;
            can.genero = gen;

            taResultados.append("--- CANCIÓN REGISTRADA ---\n");
            taResultados.append("Título: " + can.titulo + "\n");
            taResultados.append("Intérprete: " + can.nombreArtista + "\n");
            taResultados.append("Duración: " + can.duracionSegundos + " segundos\n");
            taResultados.append("Género: " + can.genero + "\n\n");

            txtTitulo.setText("");
            txtInterprete.setText("");
            txtDuracion.setText("");
            txtGenero.setText("");

            javax.swing.JOptionPane.showMessageDialog(this, "Canción creada exitosamente.");

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "La duración debe ser un número entero (segundos).");
        }
    }//GEN-LAST:event_btnCrearCancionActionPerformed

