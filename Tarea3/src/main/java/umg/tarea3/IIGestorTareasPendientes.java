    private void btnAgregarTareaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarTareaActionPerformed
        // TODO add your handling code here:
        if (indice < 5) {
            String texto = txtTarea.getText();

            tareas[indice] = texto;
            indice++;

            taLista.append(indice + ". " + texto + "\n");
            txtTarea.setText("");

            if (indice == 5) {
                javax.swing.JOptionPane.showMessageDialog(null, "Ya se ingresaron las 5 tareas.");
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(null, "Ya se registraron las 5 tareas permitidas.");
        }
    }//GEN-LAST:event_btnAgregarTareaActionPerformed

    private void btnExportarAgendaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarAgendaActionPerformed
        // TODO add your handling code here:
        if (indice < 5) {
            javax.swing.JOptionPane.showMessageDialog(null, "Debe ingresar las 5 tareas antes de exportar.");
            return;
        }

        try {
            java.io.File archivo = new java.io.File("temp/luis_agenda.txt");
            java.io.FileWriter fw = new java.io.FileWriter(archivo);
            java.io.PrintWriter pw = new java.io.PrintWriter(fw);

            pw.println("Agenda de Tareas");

            for (int i = 0; i < tareas.length; i++) {
                pw.println((i + 1) + ". " + tareas[i]);
            }

            pw.close();
            fw.close();

            javax.swing.JOptionPane.showMessageDialog(null, "Agenda exportada con exito en temp/luis_agenda.txt");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, "Error al guardar el archivo: " + e.getMessage());
        }
    }//GEN-LAST:event_btnExportarAgendaActionPerformed

