    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        String titu = txtTitulo.getText().trim();
        String con = txtConsola.getText().trim();
        String yearTexto = txtYear.getText().trim();

        if (titu.isEmpty() || con.isEmpty() || yearTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe llenar todos los campos.");
            return;
        }

        try {
            int year = Integer.parseInt(yearTexto);

            Videojuego nuevoJuego = new Videojuego(titu, con, year);

            catalogo.add(nuevoJuego);

            txtTitulo.setText("");
            txtConsola.setText("");
            txtYear.setText("");
            txtTitulo.requestFocus();

            javax.swing.JOptionPane.showMessageDialog(this, "Videojuego agregado al catalogo.");

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El año debe ser un numero entero.");
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
        // TODO add your handling code here:
        taResultado.setText("");

        if (catalogo.isEmpty()) {
            taResultado.setText("El catalogo esta vacio.\n");
            return;
        }

        taResultado.append("=== INVENTARIO DE VIDEOJUEGOS ===\n");

        for (int i = 0; i < catalogo.size(); i++) {
            Videojuego v = catalogo.get(i);
            taResultado.append((i + 1) + ". " + v.titulo + " | Consola: " + v.consola + " | Año: " + v.yearLanzamiento + "\n");
        }

        taResultado.append("\nTotal de juegos registrados: " + catalogo.size() + "\n");
    }//GEN-LAST:event_btnMostrarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if (catalogo.size() > 0) {
            int ultimoIndice = catalogo.size() - 1;
            Videojuego eliminado = catalogo.remove(ultimoIndice);

            javax.swing.JOptionPane.showMessageDialog(this, "Se elimino el último juego: " + eliminado.titulo);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No hay videojuegos en la lista para eliminar.");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

