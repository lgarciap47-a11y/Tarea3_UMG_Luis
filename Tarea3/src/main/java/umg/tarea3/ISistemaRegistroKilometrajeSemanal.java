    private void btnAgregarRutaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarRutaActionPerformed
        // TODO add your handling code here:
        if (indice < 7) {
            String texto = txtKilometraje.getText();

            double km = Double.parseDouble(texto);
            kilometrajes[indice] = km;
            indice++;

            taTotal.append("Ruta " + indice + ": " + km + " km\n");
            txtKilometraje.setText("");

            if (indice == 7) {
                javax.swing.JOptionPane.showMessageDialog(null, "Ya se ingresaron las 7 rutas.");
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(null, "Ya se registraron todas las rutas.");
        }
    }//GEN-LAST:event_btnAgregarRutaActionPerformed

    private void btnGenerarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarReporteActionPerformed
        // TODO add your handling code here:
        if (indice < 7) {
            javax.swing.JOptionPane.showMessageDialog(null, "Debe ingresar las 7 rutas primero.");
            return;
        }

        double total = 0;
        for (int i = 0; i < kilometrajes.length; i++) {
            total = total + kilometrajes[i];
        }

        double promedio = total / 7;

        taTotal.append("\nReporte Semanal de Rutas\n");
        taTotal.append("Total de Kilometros: " + total + "\n");
        taTotal.append("Promedio Diario: " + promedio + "\n");

        try {
            java.io.File archivo = new java.io.File("temp/luis_reporte_rutas.txt");
            java.io.FileWriter fw = new java.io.FileWriter(archivo);
            java.io.PrintWriter pw = new java.io.PrintWriter(fw);

            pw.println("Reporte Semanal de Rutas");
            pw.println("Total de Kilometros: " + total);
            pw.println("Promedio Diario: " + promedio);

            pw.close();
            fw.close();

            javax.swing.JOptionPane.showMessageDialog(null, "Reporte guardado con exito.");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, "Error al guardar el archivo: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGenerarReporteActionPerformed

