    private void btnCargarDatosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarDatosActionPerformed
        // TODO add your handling code here:
        try {
            java.io.File archivo = new java.io.File(rutaArchivo);
            java.util.Scanner lector = new java.util.Scanner(archivo);

            indice = 0;
            while (lector.hasNextLine() && indice < 6) {
                String linea = lector.nextLine().trim();
                if (!linea.isEmpty()) {
                    temperaturas[indice] = Double.parseDouble(linea);
                    indice++;
                }
            }
            lector.close();

            datosCargados = true;
            javax.swing.JOptionPane.showMessageDialog(null, "Datos cargados en memoria con exito.");

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, "Error al leer el archivo: " + e.getMessage());
        }
    }//GEN-LAST:event_btnCargarDatosActionPerformed

    private void btnCalcularEstadisticasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularEstadisticasActionPerformed
        // TODO add your handling code here:
        if (!datosCargados) {
            javax.swing.JOptionPane.showMessageDialog(null, "Primero debe cargar los datos desde el archivo.");
            return;
        }

        double suma = 0;
        int calidos = 0;
        int frescos = 0;

        for (int i = 0; i < temperaturas.length; i++) {
            suma = suma + temperaturas[i];

            if (temperaturas[i] >= 25.0) {
                calidos++;
            } else {
                frescos++;
            }
        }

        double promedio = suma / temperaturas.length;

        taTemperatura.setText("Analisis Climatico\n");
        taTemperatura.append("Promedio de Temperatura: " + promedio + "\n");
        taTemperatura.append("Dias Calidos (>= 25°): " + calidos + "\n");
        taTemperatura.append("Dias Frescos (< 25°): " + frescos + "\n");
    }//GEN-LAST:event_btnCalcularEstadisticasActionPerformed

