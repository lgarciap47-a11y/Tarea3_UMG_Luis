    public void cargarDatos() {
        try {
            java.io.File archivo = new java.io.File("temp/discos.csv");
            if (!archivo.exists()) {
                javax.swing.JOptionPane.showMessageDialog(this, "El archivo temp/discos.csv no existe.");
                return;
            }

            java.util.Scanner lector = new java.util.Scanner(archivo);

            int i = 0;
            while (lector.hasNextLine() && i < 5) {
                String linea = lector.nextLine().trim();
                if (!linea.isEmpty()) {
                    String[] partes = linea.split(",");
                    if (partes.length >= 2) {
                        albumes[i] = partes[0].trim();
                        year[i] = Integer.parseInt(partes[1].trim());
                        i++;
                    }
                }
            }
            lector.close();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar discos.csv: " + e.getMessage());
        }
    }

