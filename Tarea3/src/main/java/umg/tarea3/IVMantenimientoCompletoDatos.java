    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String busqueda = txtAlbum.getText().trim();

        if (busqueda.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el nombre del album a buscar.");
            return;
        }

        indiceSeleccionado = -1;

        for (int i = 0; i < albumes.length; i++) {
            if (albumes[i] != null && albumes[i].equalsIgnoreCase(busqueda)) {
                indiceSeleccionado = i;
                break;
            }
        }

        if (indiceSeleccionado != -1) {
            // Guarda y muestra el año original/anterior
            lblAnterior.setText("Año Anterior: " + year[indiceSeleccionado]);
            lblEncontrado.setText("Año Nuevo: (pendiente)");
            txtNuevo.setText("");
            txtNuevo.requestFocus();
        } else {
            lblAnterior.setText("Año Anterior: No existe");
            lblEncontrado.setText("Año Nuevo: -");
            javax.swing.JOptionPane.showMessageDialog(this, "El album no fue encontrado en la biblioteca.");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarRegistroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarRegistroActionPerformed
        // TODO add your handling code here:
        if (indiceSeleccionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Primero debe buscar un album existente para actualizarlo.");
            return;
        }

        String nuevoYearTexto = txtNuevo.getText().trim();
        if (nuevoYearTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el nuevo año.");
            return;
        }

        try {
            int nuevoYear = Integer.parseInt(nuevoYearTexto);

            // Guardamos una copia del año que tenía antes de sobreescribirlo
            int yearViejo = year[indiceSeleccionado];

            // 1. Actualizar arreglo en memoria
            year[indiceSeleccionado] = nuevoYear;

            // 2. Sobrescribir el archivo discos.csv
            java.io.File archivo = new java.io.File("temp/discos.csv");
            java.io.FileWriter fw = new java.io.FileWriter(archivo, false);
            java.io.PrintWriter pw = new java.io.PrintWriter(fw);

            for (int i = 0; i < albumes.length; i++) {
                pw.println(albumes[i] + "," + year[i]);
            }

            pw.close();
            fw.close();

            // 3. Mantener el año anterior visible y colocar el nuevo año en lblEncontrado
            lblAnterior.setText("Año Anterior: " + yearViejo);
            lblEncontrado.setText("Año Actualizado: " + nuevoYear);

            javax.swing.JOptionPane.showMessageDialog(this, "Registro actualizado y archivo guardado con exito.");

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El año debe ser un numero entero valido.");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al actualizar el archivo: " + e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarRegistroActionPerformed

